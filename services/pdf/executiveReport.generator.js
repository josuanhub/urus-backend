const PDFDocument = require("pdfkit");
const fs = require("fs");
const path = require("path");

async function generateExecutiveReport(data) {

  const {
    municipality_name,
    executive_summary,
    findings,
    evidence_chains,
    strategic_recommendations,
    funding_analysis
  } = data;

  const reportsDir = path.join(__dirname, "../../generated_reports");

  if (!fs.existsSync(reportsDir)) {
    fs.mkdirSync(reportsDir, { recursive: true });
  }

  const fileName = `report-${Date.now()}.pdf`;

  const filePath = path.join(reportsDir, fileName);

  const doc = new PDFDocument({
    margin: 50,
    size: "A4",
    bufferPages: true
  });

  doc.pipe(fs.createWriteStream(filePath));

  // =====================================================
  // COLORS
  // =====================================================

  const COLORS = {
    black: "#0A0A0A",
    gold: "#C6A15B",
    gray: "#6B7280",
    light: "#E5E7EB",
    white: "#FFFFFF"
  };

  // =====================================================
  // COVER PAGE
  // =====================================================

  doc.rect(0, 0, 595, 842).fill(COLORS.black);

  doc.fillColor(COLORS.gold)
     .rect(40, 60, 6, 720)
     .fill();

  doc.fillColor(COLORS.white)
     .fontSize(28)
     .text("URUS", 80, 120);

  doc.fontSize(18)
     .fillColor(COLORS.gold)
     .text("Operational Intelligence Report", 80, 165);

  doc.moveDown(4);

  doc.fillColor(COLORS.white)
     .fontSize(24)
     .text(municipality_name || "Unknown Municipality", 80, 260);

  doc.moveDown(2);

  doc.fillColor(COLORS.gray)
     .fontSize(11)
     .text("CONFIDENTIAL EXECUTIVE BRIEFING", 80, 330);

  doc.text(`Generated: ${new Date().toLocaleDateString()}`, 80, 350);

  doc.text("Generated by URUS Operational Intelligence System", 80, 370);

  // =====================================================
  // EXECUTIVE SUMMARY
  // =====================================================

  doc.addPage();

  doc.fillColor(COLORS.black)
     .fontSize(24)
     .text("Executive Summary");

  doc.moveDown(2);

  doc.fontSize(12)
     .fillColor("#333333")
     .text(
       executive_summary ||
       "No executive summary available.",
       {
         lineGap: 6
       }
     );

  // =====================================================
  // OPERATIONAL FINDINGS
  // =====================================================

  doc.addPage();

  doc.fontSize(24)
     .fillColor(COLORS.black)
     .text("Operational Findings");

  doc.moveDown(2);

  (findings || []).forEach((finding, index) => {

    doc
      .roundedRect(50, doc.y, 500, 70, 6)
      .fillAndStroke("#F9FAFB", "#D1D5DB");

    doc
      .fillColor(COLORS.black)
      .fontSize(12)
      .text(`Finding #${index + 1}`, 70, doc.y - 60);

    doc
      .fillColor("#333333")
      .fontSize(10)
      .text(finding, 70, doc.y - 40, {
        width: 450
      });

    doc.moveDown(4);
  });

  // =====================================================
  // OPERATIONAL SCORECARD
  // =====================================================

  doc.addPage();

  doc.fontSize(24)
     .fillColor(COLORS.black)
     .text("Operational Scorecard");

  doc.moveDown(2);

  const scorecards = [
    { label: "Infrastructure Stability", score: 72 },
    { label: "Funding Readiness", score: 84 },
    { label: "Operational Risk Exposure", score: 63 },
    { label: "Digital Coordination Capacity", score: 41 }
  ];

  scorecards.forEach((item) => {

    doc
      .fillColor(COLORS.black)
      .fontSize(12)
      .text(item.label);

    doc.moveDown(0.3);

    doc
      .rect(50, doc.y, 400, 14)
      .fill(COLORS.light);

    doc
      .rect(50, doc.y - 14, item.score * 4, 14)
      .fill(COLORS.black);

    doc
      .fillColor(COLORS.black)
      .fontSize(10)
      .text(`${item.score}%`, 470, doc.y - 12);

    doc.moveDown(1.5);
  });

  // =====================================================
  // FUNDING MATRIX
  // =====================================================

  doc.addPage();

  doc.fontSize(24)
     .fillColor(COLORS.black)
     .text("Funding Opportunity Matrix");

  doc.moveDown(2);

  const fundingPrograms = [
    {
      program: "FEMA HMGP",
      agency: "FEMA",
      value: "$2.4M"
    },
    {
      program: "CDBG-DR",
      agency: "HUD",
      value: "$4.1M"
    },
    {
      program: "Energy Resilience Program",
      agency: "DOE",
      value: "$1.2M"
    }
  ];

  doc
    .rect(50, doc.y, 500, 25)
    .fill(COLORS.black);

  doc
    .fillColor(COLORS.white)
    .fontSize(11)
    .text("PROGRAM", 60, doc.y - 18)
    .text("AGENCY", 260, doc.y - 18)
    .text("VALUE", 420, doc.y - 18);

  doc.moveDown(2);

  fundingPrograms.forEach((item) => {

    const y = doc.y;

    doc
      .rect(50, y, 500, 32)
      .stroke("#D1D5DB");

    doc
      .fillColor(COLORS.black)
      .fontSize(10)
      .text(item.program, 60, y + 10)
      .text(item.agency, 260, y + 10)
      .text(item.value, 420, y + 10);

    doc.moveDown(2);
  });

  // =====================================================
  // EVIDENCE CHAINS
  // =====================================================

  doc.addPage();

  doc.fontSize(24)
     .fillColor(COLORS.black)
     .text("Evidence Chains");

  doc.moveDown(2);

  (evidence_chains || []).forEach((chain, index) => {

    doc
      .roundedRect(50, doc.y, 500, 65, 6)
      .fillAndStroke("#F9FAFB", "#D1D5DB");

    doc
      .fillColor(COLORS.black)
      .fontSize(11)
      .text(`Chain #${index + 1}`, 70, doc.y - 55);

    doc
      .fillColor("#333333")
      .fontSize(10)
      .text(chain, 70, doc.y - 35, {
        width: 450
      });

    doc.moveDown(4);
  });

  // =====================================================
  // STRATEGIC RECOMMENDATIONS
  // =====================================================

  doc.addPage();

  doc.fontSize(24)
     .fillColor(COLORS.black)
     .text("Strategic Recommendations");

  doc.moveDown(2);

  (strategic_recommendations || []).forEach((recommendation, index) => {

    doc
      .circle(60, doc.y + 6, 4)
      .fill(COLORS.gold);

    doc
      .fillColor(COLORS.black)
      .fontSize(11)
      .text(recommendation, 80, doc.y - 8, {
        width: 450
      });

    doc.moveDown(2);
  });

  // =====================================================
  // FUNDING ANALYSIS
  // =====================================================

  doc.addPage();

  doc.fontSize(24)
     .fillColor(COLORS.black)
     .text("Funding Analysis");

  doc.moveDown(2);

  doc
    .roundedRect(50, doc.y, 500, 140, 8)
    .fillAndStroke("#F9FAFB", "#D1D5DB");

  doc
    .fillColor("#333333")
    .fontSize(11)
    .text(
      funding_analysis ||
      "No funding analysis available.",
      70,
      doc.y - 120,
      {
        width: 450,
        lineGap: 5
      }
    );

  // =====================================================
  // FOOTERS
  // =====================================================

  const pages = doc.bufferedPageRange();

  for (let i = 0; i < pages.count; i++) {

    doc.switchToPage(i);

    doc
      .fontSize(9)
      .fillColor("#9CA3AF")
      .text(
        `URUS Operational Intelligence • Page ${i + 1}`,
        50,
        810,
        {
          align: "center",
          width: 500
        }
      );
  }

  doc.end();

  return {
    ok: true,
    fileName,
    filePath
  };
}

module.exports = {
  generateExecutiveReport
};
